import logger from '../config/logger.js';

/**
 * Generate a CloudFormation template from architecture nodes and edges
 * Maps AWS service nodes to CloudFormation resource definitions
 * @param {Array} nodes - Architecture nodes
 * @param {Array} edges - Architecture edges
 * @param {string} architectureName - Name of the architecture
 * @param {string} region - AWS region (optional, for region-specific defaults)
 */
export const generateCloudFormationTemplate = (nodes, edges, architectureName, region = 'us-east-1') => {
  const resources = {};
  const outputs = {};
  const parameters = {};
  const mappings = {};
  const nodeMap = {}; // Track node IDs to resource logical IDs

  // Add default parameters for sensitive data
  parameters.DBPassword = {
    Type: 'String',
    NoEcho: true,
    Description: 'Database master password',
    MinLength: 8,
    Default: 'ChangeMe123!',
  };

  // Add region parameter (optional, can be used in mappings)
  parameters.AWSRegion = {
    Type: 'String',
    Default: region,
    Description: 'AWS region for deployment',
  };

  // Process each node
  nodes.forEach((node) => {
    const { data } = node;
    const serviceType = data.serviceType;
    const logicalId = sanitizeLogicalId(`${serviceType}${node.id.replace('node_', '')}`);
    nodeMap[node.id] = logicalId;

    try {
      const generator = serviceGenerators[serviceType];
      if (generator) {
        resources[logicalId] = generator(data, logicalId, nodeMap, region);
      } else {
        logger.warn(`No generator for service type: ${serviceType}, skipping`);
      }
    } catch (error) {
      logger.error(`Error generating resource for ${serviceType}:`, error);
    }
  });

  // Add Lambda execution role if Lambda functions exist
  const hasLambda = nodes.some(node => node.data.serviceType === 'lambda');
  if (hasLambda && !resources.LambdaExecutionRole) {
    resources.LambdaExecutionRole = {
      Type: 'AWS::IAM::Role',
      Properties: {
        AssumeRolePolicyDocument: {
          Version: '2012-10-17',
          Statement: [{
            Effect: 'Allow',
            Principal: { Service: 'lambda.amazonaws.com' },
            Action: 'sts:AssumeRole',
          }],
        },
        ManagedPolicyArns: [
          'arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole',
        ],
      },
    };
  }

  // Generate outputs for key resources
  Object.entries(resources).forEach(([logicalId, resource]) => {
    generateOutputsForResource(logicalId, resource, outputs);
  });

  const template = {
    AWSTemplateFormatVersion: '2010-09-09',
    Description: `CloudFormation template for ${architectureName}. Generated by CloudCanvas-Architect.`,
    Parameters: Object.keys(parameters).length > 0 ? parameters : undefined,
    Mappings: Object.keys(mappings).length > 0 ? mappings : undefined,
    Resources: resources,
    Outputs: Object.keys(outputs).length > 0 ? outputs : undefined,
  };

  // Remove undefined properties
  Object.keys(template).forEach(key => {
    if (template[key] === undefined) delete template[key];
  });

  return template;
};

// Helper function to sanitize logical IDs
const sanitizeLogicalId = (id) => {
  return id.replace(/[^a-zA-Z0-9]/g, '').replace(/^[0-9]/, 'R$&');
};

