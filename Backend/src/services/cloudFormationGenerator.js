/**
 * Get default AMI ID for EC2 instance
 * Prefers SSM Parameter Store (region-aware, always up-to-date)
 * Falls back to hardcoded AMI if SSM not available
 */
const getDefaultAMI = (region, customAmiId) => {
  if (customAmiId) {
    return customAmiId;
  }
  
  // Use SSM Parameter Store to get latest Amazon Linux 2 AMI
  // This is the AWS-recommended approach and automatically gets the correct AMI for the region
  return {
    'Fn::Sub': '{{resolve:ssm:/aws/service/ami-amazon-linux-latest/amzn2-ami-hvm-x86_64-gp2}}'
  };
};

// Helper function to generate outputs
const generateOutputsForResource = (logicalId, resource, outputs) => {
  const outputGenerators = {
    'AWS::EC2::Instance': () => {
      outputs[`${logicalId}PublicIP`] = {
        Description: `Public IP address of ${logicalId}`,
        Value: { 'Fn::GetAtt': [logicalId, 'PublicIp'] },
        Export: { Name: { 'Fn::Sub': `\${AWS::StackName}-${logicalId}-PublicIP` } },
      };
    },
    'AWS::RDS::DBInstance': () => {
      outputs[`${logicalId}Endpoint`] = {
        Description: `Database endpoint for ${logicalId}`,
        Value: { 'Fn::GetAtt': [logicalId, 'Endpoint.Address'] },
        Export: { Name: { 'Fn::Sub': `\${AWS::StackName}-${logicalId}-Endpoint` } },
      };
    },
    'AWS::S3::Bucket': () => {
      outputs[`${logicalId}Name`] = {
        Description: `S3 bucket name for ${logicalId}`,
        Value: { Ref: logicalId },
        Export: { Name: { 'Fn::Sub': `\${AWS::StackName}-${logicalId}-Name` } },
      };
    },
    'AWS::Lambda::Function': () => {
      outputs[`${logicalId}Arn`] = {
        Description: `ARN of Lambda function ${logicalId}`,
        Value: { 'Fn::GetAtt': [logicalId, 'Arn'] },
        Export: { Name: { 'Fn::Sub': `\${AWS::StackName}-${logicalId}-Arn` } },
      };
    },
    'AWS::ElasticLoadBalancingV2::LoadBalancer': () => {
      outputs[`${logicalId}DNS`] = {
        Description: `DNS name of ${logicalId}`,
        Value: { 'Fn::GetAtt': [logicalId, 'DNSName'] },
        Export: { Name: { 'Fn::Sub': `\${AWS::StackName}-${logicalId}-DNS` } },
      };
    },
    'AWS::DynamoDB::Table': () => {
      outputs[`${logicalId}Name`] = {
        Description: `DynamoDB table name for ${logicalId}`,
        Value: { Ref: logicalId },
        Export: { Name: { 'Fn::Sub': `\${AWS::StackName}-${logicalId}-Name` } },
      };
    },
  };

  const generator = outputGenerators[resource.Type];
  if (generator) {
    generator();
  }
};

